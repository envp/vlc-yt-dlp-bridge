use sha2::{Digest, Sha256};
use std::error::Error;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::{env, fs};

const VLC_VERSION: &str = "3.0.24";
const VLC_SHA256: &str = "8e8afc1bc205bdc578c439b2c930f77ec8da55c6f2f1a6f48ad0d38144aeab49";

fn run(command: &mut Command) -> io::Result<()> {
    let status = command.status()?;
    if status.success() {
        Ok(())
    } else {
        Err(io::Error::other(format!(
            "{command:?} failed with {status}"
        )))
    }
}

fn vlc_headers(out: &Path) -> Result<PathBuf, Box<dyn Error>> {
    if let Some(path) = env::var_os("VLC_INCLUDE_DIR") {
        let path = PathBuf::from(path).canonicalize()?;
        if !path.join("vlc_plugin.h").is_file() {
            return Err("VLC_INCLUDE_DIR must contain the VLC 3.0.24 headers".into());
        }
        return Ok(path);
    }

    let include = format!("vlc-{VLC_VERSION}/include");
    let archive = out.join("vlc-source.zip");
    let ready = out.join("vlc-headers-verified");
    if !ready.is_file() || !out.join(&include).join("vlc_plugin.h").is_file() {
        run(Command::new("curl.exe")
            .args([
                "--fail",
                "--location",
                "--silent",
                "--show-error",
                "--max-time",
                "120",
                "--output",
            ])
            .arg(&archive)
            .arg(format!(
                "https://codeload.github.com/videolan/vlc/zip/refs/tags/{VLC_VERSION}"
            )))?;
        let hash = Sha256::digest(fs::read(&archive)?);
        if format!("{hash:x}") != VLC_SHA256 {
            return Err("The VLC archive checksum did not match".into());
        }
        run(Command::new("tar.exe")
            .args(["-xf"])
            .arg(&archive)
            .arg("-C")
            .arg(out)
            .arg(&include))?;
        fs::write(ready, VLC_SHA256)?;
        fs::remove_file(archive)?;
    }
    Ok(out.join(include))
}

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=native/bridge.c");
    println!("cargo:rerun-if-changed=native/vlccore.def");
    println!("cargo:rerun-if-env-changed=VLC_INCLUDE_DIR");
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("Cargo output directory"));
    let mut config = cbindgen::Config {
        language: cbindgen::Language::C,
        include_guard: Some("YOUTUBE_BRIDGE_H".into()),
        autogen_warning: Some("/* Generated by cbindgen. */".into()),
        ..Default::default()
    };
    config.export.exclude = vec!["ShellExecuteW".into(), "PeekNamedPipe".into()];
    cbindgen::Builder::new()
        .with_config(config)
        .with_src("src/ffi.rs")
        .with_src("src/process.rs")
        .generate()?
        .write_to_file(out.join("youtube_bridge.h"));

    let target = env::var("TARGET")?;
    if env::var_os("CARGO_FEATURE_NATIVE_PLUGIN").is_none() || !target.contains("windows") {
        return Ok(());
    }
    if target != "x86_64-pc-windows-msvc" {
        return Err("Build the native VLC plugin for x86_64-pc-windows-msvc".into());
    }

    let headers = vlc_headers(&out)?;
    let clang = cc::Build::new()
        .compiler("clang-cl.exe")
        .try_get_compiler()?;
    let object = out.join("bridge.obj");
    run(clang
        .to_command()
        .args([
            "/nologo",
            "/c",
            "/O2",
            "/MD",
            "/DHAVE_STDINT_H",
            "/clang:-std=gnu11",
            "/clang:-Wno-deprecated-declarations",
            "/clang:-Wno-macro-redefined",
        ])
        .arg("/I")
        .arg(&headers)
        .arg("/I")
        .arg(&out)
        .arg(format!("/Fo{}", object.display()))
        .arg("native/bridge.c"))?;

    let lib = cc::windows_registry::find_tool(&target, "lib.exe")
        .ok_or("Install the Microsoft C++ x64 build tools and Windows SDK")?;
    let imports = out.join("vlccore.lib");
    run(lib
        .to_command()
        .args(["/nologo", "/machine:x64", "/def:native/vlccore.def"])
        .arg(format!("/out:{}", imports.display())))?;

    println!("cargo:rustc-link-arg-cdylib={}", object.display());
    println!("cargo:rustc-link-arg-cdylib={}", imports.display());
    Ok(())
}
